"""summary node — conversation summary at completion (CM-5).

Generates a concise summary (customer, issue, captured data, classification,
outcome) with gpt-4o-mini, stores it on the conversation AND the case, and
records the LLM cost on the current message (D6 via T3.6 costs).

The escalation path does NOT go through this node since T4.4: the handoff
node calls the same `generate_summary` and owns the escalation reply + state
transition + deriva bundle (HH-2). This node only serves capture completion.
"""

from __future__ import annotations

from sqlalchemy import select

from app.chat.state import ConversationState
from app.db import session_scope
from app.models import Case, Conversation, Customer
from app.services import prompts
from app.services.costs import record_llm_cost
from app.services.llm import CHAT_MODEL, openai_client


def _summary_context(state: ConversationState, customer: Customer) -> dict:
    """Return the prompt-template slot values for a summary render (task 3.3).

    The customer name falls back to the phone when absent, matching the
    pre-change f-string. ``generate_summary`` renders these into
    ``prompts/summary.md``.
    """
    name = customer.name if customer else None
    return {
        "name": name or state.phone,
        "phone": state.phone,
        "conversation_id": state.conversation_id,
        "turn": state.turn,
        "intent": state.intent,
        "case": state.case or {},
        "captured": state.captured or {},
        "escalate": state.escalate,
        "escalate_reason": state.escalate_reason or "-",
    }


def generate_summary(state: ConversationState, customer: Customer | None) -> str:
    """LLM summary persisted on conversation + case (CM-5); returns the text.

    Shared by the summary node (completion) and the handoff node (escalation,
    T4.4). Records the LLM cost on the current message (D6).
    """
    context = _summary_context(state, customer)

    client = openai_client()
    response = client.chat.completions.create(
        model=CHAT_MODEL,
        messages=[
            {"role": "system", "content": prompts.load("personas/summary.md")},
            {"role": "user", "content": prompts.render("prompts/summary.md", **context)},
        ],
        temperature=0,
    )
    summary_text = (response.choices[0].message.content or "").strip()

    with session_scope() as session:
        conv = session.get(Conversation, state.conversation_id)
        if conv is not None:
            conv.summary = summary_text
        case = session.scalar(
            select(Case)
            .where(Case.conversation_id == state.conversation_id)
            .order_by(Case.id.desc())
            .limit(1)
        )
        if case is not None:
            case.summary = summary_text
        record_llm_cost(
            session,
            message_id=state.window[-1]["id"] if state.window else 0,
            model=CHAT_MODEL,
            prompt_tokens=response.usage.prompt_tokens,
            completion_tokens=response.usage.completion_tokens,
        )
    return summary_text


def summary(state: ConversationState) -> dict:
    """CM-5: summary at completion (capture finished); escalation summaries
    are generated by the handoff node."""
    with session_scope() as session:
        customer = session.get(Customer, state.customer_id)
    return {"summary": generate_summary(state, customer)}
